import nodemailer, { type Transporter } from "nodemailer";
import { ContactRecord } from "../validators";
import { siteConfig } from "@/content/site";

export interface EmailDeliveryResult {
  success: boolean;
  mode: "live" | "ethereal" | "mock";
  type: "notification" | "autoreply";
  to: string;
  subject: string;
  body: string;
  previewUrl?: string;
  message: string;
  error?: string;
}

export interface EmailProvider {
  sendNotification(record: ContactRecord): Promise<EmailDeliveryResult>;
  sendAutoReply(record: ContactRecord): Promise<EmailDeliveryResult>;
}

