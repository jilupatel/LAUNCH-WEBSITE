class SmtpEmailProvider implements EmailProvider {
  private transporter: Transporter;
  private fromAddress: string;
  private toAddress: string;

  constructor() {
    this.fromAddress =
      process.env.EMAIL_FROM || `"${siteConfig.name}" <${siteConfig.contact.email}>`;
    this.toAddress = process.env.EMAIL_TO || siteConfig.contact.email;

    const host = process.env.SMTP_HOST || "smtp.gmail.com";
    const port = parseInt(process.env.SMTP_PORT || "465", 10);
    const secure = port === 465;

    this.transporter = nodemailer.createTransport({
      host,
      port,
      secure,
      auth: {
        user: process.env.SMTP_USER || "",
        pass: process.env.SMTP_PASS || "",
      },
    });
  }

  async sendNotification(record: ContactRecord): Promise<EmailDeliveryResult> {
    const { subject, text, html } = generateNotificationContent(record);
    try {
      await this.transporter.sendMail({
        from: this.fromAddress,
        to: this.toAddress,
        subject,
        text,
        html,
      });

      return {
        success: true,
        mode: "live",
        type: "notification",
        to: this.toAddress,
        subject,
        body: text,
        message: `Notification email sent to ${this.toAddress} via SMTP.`,
      };
    } catch (err: unknown) {
      const errorMessage = err instanceof Error ? err.message : String(err);
      return {
        success: false,
        mode: "live",
        type: "notification",
        to: this.toAddress,
        subject,
        body: text,
        message: "Failed to send notification email via SMTP.",
        error: errorMessage,
      };
    }
  }

  async sendAutoReply(record: ContactRecord): Promise<EmailDeliveryResult> {
    const { subject, text, html } = generateAutoReplyContent(record);
    try {
      await this.transporter.sendMail({
        from: this.fromAddress,
        to: record.email,
        subject,
        text,
        html,
      });

      return {
        success: true,
        mode: "live",
        type: "autoreply",
        to: record.email,
        subject,
        body: text,
        message: `Auto-reply email sent to ${record.email} via SMTP.`,
      };
    } catch (err: unknown) {
      const errorMessage = err instanceof Error ? err.message : String(err);
      return {
        success: false,
        mode: "live",
        type: "autoreply",
        to: record.email,
        subject,
        body: text,
        message: "Failed to send auto-reply email via SMTP.",
        error: errorMessage,
      };
    }
  }
}

class EtherealEmailProvider implements EmailProvider {
  private fromAddress: string;
  private toAddress: string;

  constructor() {
    this.fromAddress = `"${siteConfig.name}" <inquiries@ethereal.email>`;
    this.toAddress = process.env.EMAIL_TO || "client-inquiries@ethereal.email";
  }

  private async createEtherealTransporter() {
    const testAccount = await nodemailer.createTestAccount();
    return nodemailer.createTransport({
      host: testAccount.smtp.host,
      port: testAccount.smtp.port,
      secure: testAccount.smtp.secure,
      auth: {
        user: testAccount.user,
        pass: testAccount.pass,
      },
    });
  }

  async sendNotification(record: ContactRecord): Promise<EmailDeliveryResult> {
    const { subject, text, html } = generateNotificationContent(record);
    try {
      const transporter = await this.createEtherealTransporter();
      const info = await transporter.sendMail({
        from: this.fromAddress,
        to: this.toAddress,
        subject,
        text,
        html,
      });

      const previewUrl = nodemailer.getTestMessageUrl(info) || undefined;
      return {
        success: true,
        mode: "ethereal",
        type: "notification",
        to: this.toAddress,
        subject,
        body: text,
        previewUrl,
        message: `Notification email created in Ethereal throwaway inbox.`,
      };
    } catch (err: unknown) {
      const errorMessage = err instanceof Error ? err.message : String(err);
      return {
        success: false,
        mode: "ethereal",
        type: "notification",
        to: this.toAddress,
        subject,
        body: text,
        message: "Failed to send Ethereal notification email.",
        error: errorMessage,
      };
    }
  }

  async sendAutoReply(record: ContactRecord): Promise<EmailDeliveryResult> {
    const { subject, text, html } = generateAutoReplyContent(record);
    try {
      const transporter = await this.createEtherealTransporter();
      const info = await transporter.sendMail({
        from: this.fromAddress,
        to: record.email,
        subject,
        text,
        html,
      });

      const previewUrl = nodemailer.getTestMessageUrl(info) || undefined;
      return {
        success: true,
        mode: "ethereal",
        type: "autoreply",
        to: record.email,
        subject,
        body: text,
        previewUrl,
        message: `Auto-reply confirmation created in Ethereal throwaway inbox.`,
      };
    } catch (err: unknown) {
      const errorMessage = err instanceof Error ? err.message : String(err);
      return {
        success: false,
        mode: "ethereal",
        type: "autoreply",
        to: record.email,
        subject,
        body: text,
        message: "Failed to send Ethereal auto-reply email.",
        error: errorMessage,
      };
    }
  }
}

class MockEmailProvider implements EmailProvider {
  async sendNotification(record: ContactRecord): Promise<EmailDeliveryResult> {
    const { subject, text } = generateNotificationContent(record);
    const to = process.env.EMAIL_TO || siteConfig.contact.email;
    return {
      success: true,
      mode: "mock",
      type: "notification",
      to,
      subject,
      body: text,
      message: `[DEMO] Lead alert generated for business owner (${to}).`,
    };
  }

  async sendAutoReply(record: ContactRecord): Promise<EmailDeliveryResult> {
    const { subject, text } = generateAutoReplyContent(record);
    return {
      success: true,
      mode: "mock",
      type: "autoreply",
      to: record.email,
      subject,
      body: text,
      message: `[DEMO] Instant auto-reply confirmation dispatched to customer (${record.email}).`,
    };
  }
}

export function getEmailProvider(): EmailProvider {
  const providerType = process.env.EMAIL_PROVIDER?.trim().toLowerCase();

  if (providerType === "smtp") {
    return new SmtpEmailProvider();
  }

  if (providerType === "ethereal") {
    return new EtherealEmailProvider();
  }

  return new MockEmailProvider();
}
